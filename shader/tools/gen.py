#!/usr/bin/env python3
"""Generate everything that depends on src/params.json and src/overlay.glsl:
  Assets/Shaders/ElementalOverlay.cginc        HLSL overlay for the Unity shader
  ../mod/Params.g.cs                                    BepInEx config entries + shader globals push
  preview/overlay.gen.js                       GLSL + schema for the browser preview
Run from anywhere: python3 tools/gen.py
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT.parent / "mod"
schema = json.loads((ROOT / "src/params.json").read_text())
src = (ROOT / "src/overlay.glsl").read_text()

bad = re.findall(r"\bvec[234]\(\s*[^,()]*\)", src)
if bad:
    sys.exit(f"single-argument vector constructors don't translate to HLSL, use v3(): {bad}")

params = [(s["name"], p) for s in schema["sections"] for p in s["params"]]
uniforms = [(f"_{sec}{p[0]}", p) for sec, p in params if p[1] in ("f", "c", "b")]

ENGINE_GLSL = "uniform vec4 _ElemA; uniform vec4 _ElemAge; uniform float _ElemB; uniform float _ElemLight; uniform float _ElemCutoff; uniform vec3 _ElemSunDir; uniform float uTime;\n"
ENGINE_HLSL = "float4 _ElemA; float4 _ElemAge; float _ElemB; float _ElemLight; float _ElemCutoff; float3 _ElemSunDir;\n#define uTime _Time.y\n"


def to_hlsl(s):
    for a, b in [(r"\bvec([234])\b", r"float\1"), (r"\bmix\(", "lerp("), (r"\bfract\(", "frac("),
                 (r"\binversesqrt\(", "rsqrt("), (r"\bdFdx\(", "ddx("), (r"\bdFdy\(", "ddy(")]:
        s = re.sub(a, b, s)
    return s


def srgb(c):
    return [12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055 for x in c]


banner = "// <auto-generated> by tools/gen.py from src/params.json and src/overlay.glsl. Do not edit.\n"

# --- HLSL include ---
decl = "".join(f"{'float3' if p[1] == 'c' else 'float'} {u};\n" for u, p in uniforms)
(ROOT / "Assets/Shaders/ElementalOverlay.cginc").write_text(
    banner + "#ifndef ELEMENTAL_OVERLAY_INCLUDED\n#define ELEMENTAL_OVERLAY_INCLUDED\n" + ENGINE_HLSL + decl + to_hlsl(src) + "\n#endif\n")

# --- C# config + push ---
cs = [banner, "using BepInEx.Configuration;\nusing UnityEngine;\nusing UnityEngine.Rendering;\n\nnamespace ElementalOverhaul\n{\n",
      "    // Every tunable from params.json: shader globals (pushed each frame) and particle settings.\n    public static class P\n    {\n"]
for sec, p in params:
    t = {"c": "Color", "b": "bool"}.get(p[1], "float")
    cs.append(f"        public static ConfigEntry<{t}> {sec}{p[0]};\n")
for u, p in uniforms:
    cs.append(f'        static readonly int id{u} = Shader.PropertyToID("{u}");\n')
cs.append("\n        public static void Bind(ConfigFile c)\n        {\n")
for sec, p in params:
    name, typ, d, lo, hi, desc = p
    desc = desc.replace('"', '\\"')
    if typ == "b":
        cs.append(f'            {sec}{name} = c.Bind("{sec}", "{name}", {"true" if d else "false"}, "{desc}");\n')
    elif typ == "c":
        r, g, b = srgb(d)
        cs.append(f'            {sec}{name} = c.Bind("{sec}", "{name}", new Color({r:.4f}f, {g:.4f}f, {b:.4f}f, 1f), "{desc}");\n')
    else:
        cs.append(f'            {sec}{name} = c.Bind("{sec}", "{name}", {float(d)}f, new ConfigDescription("{desc}", new AcceptableValueRange<float>({float(lo)}f, {float(hi)}f)));\n')
cs.append("        }\n\n        public static void Push(CommandBuffer cb)\n        {\n")
for u, p in uniforms:
    sec_name = u[1:]
    if p[1] == "c":
        cs.append(f"            cb.SetGlobalVector(id{u}, {sec_name}.Value.linear);\n")
    elif p[1] == "b":
        cs.append(f"            cb.SetGlobalFloat(id{u}, {sec_name}.Value ? 1f : 0f);\n")
    else:
        cs.append(f"            cb.SetGlobalFloat(id{u}, {sec_name}.Value);\n")
cs.append("        }\n    }\n}\n")
(MOD / "Params.g.cs").write_text("".join(cs))

# --- preview ---
gdecl = "".join(f"uniform {'vec3' if p[1] == 'c' else 'float'} {u};\n" for u, p in uniforms)
(ROOT / "preview").mkdir(exist_ok=True)
(ROOT / "preview/overlay.gen.js").write_text(
    banner + "const OVERLAY_GLSL = `\n" + ENGINE_GLSL + gdecl + src + "`;\nconst PARAM_SCHEMA = " + json.dumps(schema["sections"]) + ";\n")
print(f"generated: {len(params)} params, {len(uniforms)} shader uniforms")
